                                    <h2>How does it Work?</h2>
                                    <p>The sun is a renewable source of energy that can emit light for a billion years 
                                    without costing you anything.</p>
                                    <p>Let's talk about how solar energy works. Solar energy is the energy coming from 
                                    the sun that is used to produce electricity.</p>
                                    <p>Light rays coming from the sun get trapped by the solar plates, and solar cells 
                                    convert that light to energy, which is known as the photovoltaic effect.</p>
                                    <p>Simply, THE SUN→SOLAR PANELS→ELECTRICITY</p>
                                    <div class="text-center">
