                                    <h2>The Benefits of Choosing Solar Energy</h2>
                                    <h3 class="benifits-heading">Availability:</h3>
                                    <div class="text-center">
                                    <img src="public/images/blog52.jpg" class="img-fluid text-center mt-3 mb-5" alt="sun-is-available-all-the-time">
                                    </div>
                                    <p>No matter where you live or go, the sun is always there, as it is a natural source of 
                                    energy and available for free. Many people think that solar power will only work if 
                                    there is the sun, but that is actually not true.</p>
                                    <p>Your solar panel will generate energy irrespective of weather conditions, whether it is a rainy or 
                                    cloudy day.</p>
                                    <h3 class="benifits-heading">Maintenance Free:</h3>
                                    <div class="text-center">
                                    <img src="public/images/blog53.jpg" class="img-fluid text-center" alt="maintenance-of-solar-panels-is-free-of-cost">
                                    </div>
                                    <p>Unlike any other machine, solar does not have any moving parts that need to be 
                                    maintained and replaced every year. Cleaning requires only a clean cloth and 
                                    water. You heard right, you don’t need to spend any money on maintenance. You 
                                    just need to take care that there is no dirt on the solar plates and you can clean 
                                    them every once in 6 months.</p>
                                    <h3 class="benifits-heading">Environment Friendly:</h3>
                                    <div class="text-center">
                                    <img src="public/images/blog54.jpg" class="img-fluid text-center mt-3 mb-5" alt="solar-power-is-an-environmentally-friendly-source-of-energy">
                                    </div>
                                    <p>As we know, solar is a clean source of energy and it doesn't emit any greenhouse 
                                    gases which can harm the environment, so it is pollution-free and eco-friendly to 
                                    the environment and also does not cause any harm to humans either.</p>
                                    <h3 class="benifits-heading">Cost Effective:</h3>
                                    <div class="text-center">
                                    <img src="public/images/blog55.jpg" class="img-fluid text-center" alt="solar-is-cost-effective-in-nature">
                                    </div>
                                    <p>Solar energy is a cost-effective method and starts working the day you install it. Yes, it costs a 
                                    bit initially, but from your electricity bill it compensates all your expenses within 3 to 4 years, and
                                    then after that you can use free electricity for 20 years. You can even earn money by selling 
                                    excess energy to power plants or government agencies.</p>
                                    <h3 class="benifits-heading">Property Worth:</h3>
                                    <div class="text-center">
                                    <img src="public/images/blog56.jpg" class="img-fluid text-center" alt="solar-increses-property-value">
                                    </div>
                                    <p>I know you all are wondering how solar power can make your property worth 
                                    more. Yes, it is true that solar rooftop can do it. Let’s see how.</p>
                                    <p>While selling, the property value gets decided on amenities and features the 
                                    property has, and a solar rooftop can be that worth-affecting feature. Having a 
                                    solar panel can help buyers save money and reduce their electricity bill in the 
                                    future. For that reason, you can get more money for your property.</p>
