                                            <h2>How does it Work?</h2>
                                            <p>The solar cells which are present in solar panels also referred to as photovoltaic cells, absorb sunlight during daylight hours. Within each solar cell there is a thin semiconductor wafer made from two layers of silicon. One layer is positively charged and other is negatively charged, forming an electric field. When sunlight strikes a solar cell, it energizes the cell and causes electrons to ‘come loose’ from atoms within the semiconductor wafer. Those loose electrons are set into motion by the electric field and this motion creates an electrical current.</p>
                                            <p>As solar rooftop panel is working efficiently to transform sunlight into electricity but generated electricity generated is DC (Direct Current) which is not the type of electricity that powers most homes. This DC electricity can easily be changed into AC (Alternating Current) electricity by an equipment called a solar inverter. This AC electricity from <a href="https://www.ksquareenergy.com/products/Sofar%20Inverter">solar inverter</a> is directed to your switch board in homes. Home’s switchboard will ensure that solar energy will be used first and only accessing additional energy from the grid when your solar production is not enough.</p>
                                            <p>During the formation of surplus energy in a day, Net Meter are used for collection so when it is night time or cloudy and panels are not able to capture enough sunlight to produce energy, your home is operated by collected surplus energy that is stored is net meter. For this reason meter is used to measure the electricity flowing in both directions—to and from your home.</p>
                                            <p>An unused solar electricity is sent back to the grid. Exporting solar power back to the grid earns you a credit on your electricity bill. Your electricity service provider will then take into account the electricity you purchase from the grid, plus credits for the electricity generated by your solar power system that you don’t use. <a href="https://100percentrenewables.com.au/nine-ways-maximise-financial-benefit-surplus-solar-energy/">More ways to maximise the financial benefits from surplus solar energy.</a></p>
