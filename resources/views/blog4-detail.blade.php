                                    <h2>What is Solar Energy?</h2>
                                    <p>Solar Energy is any kind of energy generated by the sun. Solar energy can be harnessed directly or indirectly for human use.</p>
                                    <p>Solar Power works by converting sunlight to electricity. This electricity can then be used and also can be exported to the grid when it’s not needed. This is achieved by installing rooftop solar which generate DC (Direct Current) electricity. This energy is then fed into a solar inverter which converts the DC electricity from your solar panels into AC (Alternating Current) electricity.</p>

