<script>
    $(document).ready(function() {
    // Hide all tab contents initially except the first one
    $('.download_tab_content').not(':first').hide();
    
    // Add active class to first tab header
    $('.tab_head:first').addClass('active');
    
    // Click handler for tab headers
    $('.tab_head').click(function() {
        // Remove active class from all headers
        $('.tab_head').removeClass('active');
        
        // Add active class to clicked header
        $(this).addClass('active');
        
        // Get the index of clicked tab
        var index = $(this).index();
        
        // Hide all tab contents
        $('.download_tab_content').hide();
        
        // Show the corresponding tab content
        $('.download_tab_content').eq(index).show();
    });
});
</script>
