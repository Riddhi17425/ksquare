$.validator.addMethod("noSpamWords", function (value, element) {
    let spamWords = [
        'seo',
        'crypto',
        'viagra',
        'casino',
        'furniture',
        'wholesale'
    ];
    let lowerValue = value.toLowerCase();
    for (let i = 0; i < spamWords.length; i++) {
        if (lowerValue.includes(spamWords[i])) {
            return false;
        }
    }
    return true;
}, "Spam content detected.");

